namespace Core.Entities
{
    public class DemandeIntervention
    {
        public int IdDemandeIntervention { get; set; }
        public string Titre { get; set; } = string.Empty;

        // Description of the problem, written by the requester
        public string? Description { get; set; }

        // Work report written by the technician when the job is done
        // (work performed, root cause, parts used). Required to complete.
        public string? CompteRendu { get; set; }

        // Set by the server at creation time, never by the client
        public DateTime DateCreation { get; set; }
        public byte[]? FileData { get; set; }
        public string? FileName { get; set; }
        public string? ContentType { get; set; }
        public bool MachineArretee { get; set; }

        // Keep the existing Etat for backward compatibility
        public int IDEtat { get; set; }
        public Etat Etat { get; set; } = null!;

        // Add the new Status relationship
        public int StatusId { get; set; }
        public Status Status { get; set; } = null!;

        public int IDTypeIntervention { get; set; }
        public TypeIntervention TypeIntervention { get; set; } = null!;
        public int IDUrgence { get; set; }
        public Urgence Urgence { get; set; } = null!;
        public int IDChaineProduction { get; set; }
        public ChaineProduction ChaineProduction { get; set; } = null!;

        // Machine concerned by the request (optional for line-level issues)
        public int? IDEquipement { get; set; }
        public Equipment? Equipement { get; set; }
        public int IDPanne { get; set; }
        public Panne Panne { get; set; } = null!;
        public int DemandeursID { get; set; }
        public Users Demandeur { get; set; } = null!;
        public int? DestinatairesID { get; set; }
        public Users? Destinataire { get; set; } = null!;
        public bool IsActif { get; set; }

        // Add fields to track workflow actions
        public DateTime? DateAssignation { get; set; }
        public DateTime? DateRealisation { get; set; }
        public DateTime? DateCloture { get; set; }
        public string? RaisonAnnulation { get; set; }

        public DateTime? DatePriseEnCharge { get; set; }
        public DateTime? DateResolution { get; set; }

        // Planning and analysis
        public DateTime? DatePlanifiee { get; set; }
        public int? DureeEstimeeMinutes { get; set; }
        public string? Cause { get; set; }
        public string? Remede { get; set; }
        // External costs (subcontracting, services) in addition to labour and parts
        public decimal? CoutExterne { get; set; }

        // Set when the work order was generated by a preventive plan
        public int? IdPlanPreventif { get; set; }
        public PlanPreventif? PlanPreventif { get; set; }

        public List<InterventionTemps> Temps { get; set; } = new();
        public List<InterventionPiece> PiecesConsommees { get; set; } = new();
        public List<InterventionTache> Taches { get; set; } = new();
        
    }
}