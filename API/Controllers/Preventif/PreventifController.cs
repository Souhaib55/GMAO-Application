        [HttpGet("plans")]
        public async Task<ActionResult<object>> GetPlans(string? search = null, int? equipementId = null, int? chaineId = null, bool? actif = null)
        {
            var today = DateTime.Today;
            var query = _context.PlansPreventifs.AsNoTracking().AsQueryable();
            if (!string.IsNullOrWhiteSpace(search))
            {
                var s = search.Trim();
                query = query.Where(p => p.Code.Contains(s) || p.Titre.Contains(s) ||
                                         p.Equipement.Designation.Contains(s) || p.Equipement.CodeEquipement.Contains(s));
            }
            if (equipementId.HasValue) query = query.Where(p => p.IdEquipement == equipementId);
            if (chaineId.HasValue) query = query.Where(p => p.Equipement.IdChaineProduction == chaineId);
            if (actif.HasValue) query = query.Where(p => p.IsActif == actif);

            var rows = await query
                .OrderBy(p => p.IsActif ? 0 : 1).ThenBy(p => p.ProchaineEcheance)
                .Select(p => new
                {
                    p.Id,
                    p.Code,
                    p.Titre,
                    p.Frequence,
                    p.Intervalle,
                    p.DureeEstimeeMinutes,
                    p.ProchaineEcheance,
                    p.DerniereGeneration,
                    p.DelaiGenerationJours,
                    p.IsActif,
                    Equipement = new { p.Equipement.IdEquipement, p.Equipement.CodeEquipement, p.Equipement.Designation },
                    Chaine = p.Equipement.ChaineProduction != null ? p.Equipement.ChaineProduction.Libelle : null,
                    Technicien = p.Technicien != null ? new { p.Technicien.ID, p.Technicien.Prenom, p.Technicien.Nom } : null,
                    NbTaches = p.Taches.Count,
                    // Latest work order generated by the plan
                    DernierOt = _context.DemandeInterventions
                        .Where(d => d.IdPlanPreventif == p.Id && d.IsActif)
                        .OrderByDescending(d => d.DatePlanifiee)
                        .Select(d => new { d.IdDemandeIntervention, d.DatePlanifiee, d.StatusId, d.DateRealisation })
                        .FirstOrDefault(),
                    OtEnRetard = _context.DemandeInterventions.Count(d =>
                        d.IdPlanPreventif == p.Id && d.IsActif && d.StatusId <= DemandeInterventionController.StatusEnCours &&
                        d.DatePlanifiee < today)
                })
                .ToListAsync();

            return Ok(rows.Select(r => new
            {
                r.Id, r.Code, r.Titre, r.Frequence, r.Intervalle,
                FrequenceLibelle = LibelleFrequence(r.Frequence, r.Intervalle),
                r.DureeEstimeeMinutes, r.ProchaineEcheance, r.DerniereGeneration, r.DelaiGenerationJours, r.IsActif,
                r.Equipement, r.Chaine, r.Technicien, r.NbTaches, r.DernierOt, r.OtEnRetard,
                JoursAvantEcheance = (int)(r.ProchaineEcheance.Date - today).TotalDays
            }));
        }

        [HttpGet("plans/{id:int}")]
        public async Task<ActionResult<object>> GetPlan(int id)
        {
            var plan = await _context.PlansPreventifs.AsNoTracking()
                .Where(p => p.Id == id)
                .Select(p => new
                {
                    p.Id, p.Code, p.Titre, p.Description, p.IdEquipement, p.IdTypeIntervention, p.Frequence, p.Intervalle,
                    p.DureeEstimeeMinutes, p.IdTechnicien, p.DateDebut, p.ProchaineEcheance, p.DerniereGeneration,
                    p.DelaiGenerationJours, p.IsActif, p.DateCreation,
                    Equipement = new { p.Equipement.IdEquipement, p.Equipement.CodeEquipement, p.Equipement.Designation },
                    Technicien = p.Technicien != null ? new { p.Technicien.ID, p.Technicien.Prenom, p.Technicien.Nom } : null,
                    Taches = p.Taches.OrderBy(t => t.Ordre).Select(t => new { t.Id, t.Ordre, t.Libelle }).ToList(),
                    Historique = _context.DemandeInterventions
                        .Where(d => d.IdPlanPreventif == p.Id && d.IsActif)
                        .OrderByDescending(d => d.DatePlanifiee)
                        .Take(24)
                        .Select(d => new
                        {
                            d.IdDemandeIntervention, d.Titre, d.DatePlanifiee, d.DateRealisation, d.StatusId,
                            Statut = d.Status.Statut,
                            Technicien = d.Destinataire != null ? d.Destinataire.Prenom + " " + d.Destinataire.Nom : null
                        })
                        .ToList()
                })
                .FirstOrDefaultAsync();

            if (plan == null) return NotFound(new { message = "Plan introuvable." });
            return Ok(new { plan, FrequenceLibelle = LibelleFrequence(plan.Frequence, plan.Intervalle) });
        }

        public class PlanDto
        {
            public string? Titre { get; set; }
            public string? Description { get; set; }
            public int IdEquipement { get; set; }
            public int? IdTypeIntervention { get; set; }
            public string? Frequence { get; set; }
            public int Intervalle { get; set; } = 1;
            public int? DureeEstimeeMinutes { get; set; }
            public int? IdTechnicien { get; set; }
            public DateTime? DateDebut { get; set; }
            public DateTime? ProchaineEcheance { get; set; }
            public int DelaiGenerationJours { get; set; } = 7;
            public bool IsActif { get; set; } = true;
            public List<string>? Taches { get; set; }
        }

        private async Task<string?> ApplyAsync(PlanPreventif plan, PlanDto dto, bool isCreate)
        {
            var titre = dto.Titre?.Trim();
            if (string.IsNullOrWhiteSpace(titre) || titre.Length < 3) return "Le titre est obligatoire (3 caractères minimum).";
            if (titre.Length > 150) return "Le titre ne doit pas dépasser 150 caractères.";
            if (dto.Description?.Length > 2000) return "La description ne doit pas dépasser 2000 caractères.";
            if (!Frequences.Contains(dto.Frequence)) return "Fréquence invalide.";
            if (dto.Intervalle < 1 || dto.Intervalle > 365) return "L'intervalle doit être compris entre 1 et 365.";
            if (dto.DureeEstimeeMinutes is < 0 or > 10080) return "Durée estimée invalide.";
            if (dto.DelaiGenerationJours < 0 || dto.DelaiGenerationJours > 60) return "Le délai de génération doit être compris entre 0 et 60 jours.";

            if (!await _context.Equipments.AnyAsync(e => e.IdEquipement == dto.IdEquipement && !e.IsDeleted))
                return "Équipement invalide.";
            if (dto.IdTypeIntervention.HasValue && !await _context.TypeInterventions.AnyAsync(t => t.IDTypeIntervention == dto.IdTypeIntervention && t.IsActif))
                return "Type d'intervention invalide.";
            if (dto.IdTechnicien.HasValue && !await _context.Users.AnyAsync(u => u.ID == dto.IdTechnicien && u.IsActif && u.Role.Libelle == Roles.Technicien))
                return "Le technicien sélectionné est invalide.";

            var taches = (dto.Taches ?? new()).Select(t => t?.Trim() ?? "").Where(t => t.Length > 0).ToList();
            if (taches.Any(t => t.Length > 255)) return "Une étape de la checklist dépasse 255 caractères.";
            if (taches.Count > 50) return "50 étapes au maximum.";

            var dateDebut = (dto.DateDebut ?? DateTime.Today).Date;
            plan.Titre = titre;
            plan.Description = string.IsNullOrWhiteSpace(dto.Description) ? null : dto.Description.Trim();
            plan.IdEquipement = dto.IdEquipement;
            plan.IdTypeIntervention = dto.IdTypeIntervention;
            plan.Frequence = dto.Frequence!;
            plan.Intervalle = dto.Intervalle;
            plan.DureeEstimeeMinutes = dto.DureeEstimeeMinutes;
            plan.IdTechnicien = dto.IdTechnicien;
            plan.DelaiGenerationJours = dto.DelaiGenerationJours;
            plan.IsActif = dto.IsActif;
            if (isCreate || dto.DateDebut.HasValue) plan.DateDebut = dateDebut;
            if (isCreate) plan.ProchaineEcheance = (dto.ProchaineEcheance ?? dateDebut).Date;
            else if (dto.ProchaineEcheance.HasValue) plan.ProchaineEcheance = dto.ProchaineEcheance.Value.Date;

            plan.Taches.Clear();
            for (var i = 0; i < taches.Count; i++)
                plan.Taches.Add(new PlanPreventifTache { Ordre = i + 1, Libelle = taches[i] });
            return null;
        }

        [HttpPost("plans")]
        public async Task<ActionResult<object>> CreatePlan([FromBody] PlanDto dto)
        {
            var user = await _currentUser.GetAsync();
            if (user == null) return Unauthorized();

            var plan = new PlanPreventif { DateCreation = DateTime.Now, CreeParId = user.Id };
            var error = await ApplyAsync(plan, dto, isCreate: true);
            if (error != null) return BadRequest(new { message = error });

            var next = (await _context.PlansPreventifs.MaxAsync(p => (int?)p.Id) ?? 0) + 1;
            plan.Code = $"PM-{next:0000}";
            while (await _context.PlansPreventifs.AnyAsync(p => p.Code == plan.Code)) plan.Code = $"PM-{++next:0000}";

            _context.PlansPreventifs.Add(plan);
            await _context.SaveChangesAsync();
            _journal.Add(user, "PlanPreventif", plan.Id, "Création", $"{plan.Code} — {plan.Titre}");
            await _context.SaveChangesAsync();

            // A plan due now gets its first work order immediately
            await _preventif.GenerateDueAsync(plan.Id, actor: user);
            return Ok(new { plan.Id, plan.Code });
        }

        [HttpPut("plans/{id:int}")]
        public async Task<ActionResult> UpdatePlan(int id, [FromBody] PlanDto dto)
        {
            var user = await _currentUser.GetAsync();
            var plan = await _context.PlansPreventifs.Include(p => p.Taches).FirstOrDefaultAsync(p => p.Id == id);
            if (plan == null) return NotFound(new { message = "Plan introuvable." });

            var error = await ApplyAsync(plan, dto, isCreate: false);
            if (error != null) return BadRequest(new { message = error });

            _journal.Add(user, "PlanPreventif", plan.Id, "Modification", plan.Code);
            await _context.SaveChangesAsync();
            await _preventif.GenerateDueAsync(plan.Id, actor: user);
            return Ok(new { plan.Id, plan.Code });
        }

        [HttpPatch("plans/{id:int}/actif")]
        public async Task<ActionResult> SetActif(int id, [FromQuery] bool actif)
        {
            var user = await _currentUser.GetAsync();
            var plan = await _context.PlansPreventifs.FirstOrDefaultAsync(p => p.Id == id);
            if (plan == null) return NotFound(new { message = "Plan introuvable." });
            plan.IsActif = actif;
            _journal.Add(user, "PlanPreventif", plan.Id, actif ? "Réactivation" : "Suspension", plan.Code);
            await _context.SaveChangesAsync();
            return Ok();
        }

        /// <summary>Creates the next work order now, whatever the generation window.</summary>
        [HttpPost("plans/{id:int}/generer")]
        public async Task<ActionResult<object>> GenerateOne(int id)
        {
            var user = await _currentUser.GetAsync();
            if (!await _context.PlansPreventifs.AnyAsync(p => p.Id == id && p.IsActif))
                return BadRequest(new { message = "Le plan est introuvable ou suspendu." });
            // Generating early must not pile up future work orders while the current one is still open
            var ouvert = await _context.DemandeInterventions.AsNoTracking()
                .Where(d => d.IdPlanPreventif == id && d.IsActif &&
                            (d.StatusId == DemandeInterventionController.StatusATraiter || d.StatusId == DemandeInterventionController.StatusEnCours))
                .OrderBy(d => d.DatePlanifiee)
                .Select(d => new { d.IdDemandeIntervention, d.DatePlanifiee })
                .FirstOrDefaultAsync();
            if (ouvert != null)
                return BadRequest(new { message = $"L'ordre de travail INT-{ouvert.IdDemandeIntervention:0000} (prévu le {ouvert.DatePlanifiee:dd/MM/yyyy}) est encore ouvert pour ce plan. Réalisez-le avant d'en générer un nouveau." });
            var results = await _preventif.GenerateDueAsync(id, force: true, actor: user);
            return Ok(new { generes = results });
        }

        /// <summary>Runs the scheduled generation now for every plan.</summary>
        [HttpPost("generer")]
        public async Task<ActionResult<object>> GenerateAll()
        {
            var user = await _currentUser.GetAsync();
            var results = await _preventif.GenerateDueAsync(actor: user);
            return Ok(new { generes = results });
        }

