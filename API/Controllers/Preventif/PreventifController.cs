    /// <summary>
    /// Preventive maintenance plans. Each plan generates its work orders automatically
    /// (background job, hourly) a few days before every due date.
    /// </summary>
    [Authorize(Roles = Roles.Superviseur + "," + Roles.Technicien)]
    [SupervisorWrites]
    [ApiController]
    [Route("api/preventif")]
    public class PreventifController : ControllerBase
    {
        // A preventive job counts as "on time" when completed within this tolerance
        public const int ToleranceJours = 2;

        private static readonly string[] Frequences =
            { PlanPreventif.FrequenceJour, PlanPreventif.FrequenceSemaine, PlanPreventif.FrequenceMois, PlanPreventif.FrequenceAnnee };

        private readonly StoreContext _context;
        private readonly ICurrentUserService _currentUser;
        private readonly IPreventifService _preventif;
        private readonly IJournalService _journal;

        public PreventifController(StoreContext context, ICurrentUserService currentUser, IPreventifService preventif, IJournalService journal)
        {
            _context = context;
            _currentUser = currentUser;
            _preventif = preventif;
            _journal = journal;
        }

        public static string LibelleFrequence(string frequence, int intervalle) => (frequence, intervalle) switch
        {
            (PlanPreventif.FrequenceJour, 1) => "Tous les jours",
            (PlanPreventif.FrequenceJour, _) => $"Tous les {intervalle} jours",
            (PlanPreventif.FrequenceSemaine, 1) => "Toutes les semaines",
            (PlanPreventif.FrequenceSemaine, _) => $"Toutes les {intervalle} semaines",
            (PlanPreventif.FrequenceAnnee, 1) => "Tous les ans",
            (PlanPreventif.FrequenceAnnee, _) => $"Tous les {intervalle} ans",
            (_, 1) => "Tous les mois",
            _ => $"Tous les {intervalle} mois"
        };

