        /// <summary>
        /// Preventive calendar: existing work orders in the range, plus the future
        /// occurrences projected from each active plan.
        /// </summary>
        [HttpGet("calendrier")]
        public async Task<ActionResult<object>> GetCalendar(DateTime from, DateTime to, int? chaineId = null)
        {
            from = from.Date;
            to = to.Date;
            if (to < from || (to - from).TotalDays > 400) return BadRequest(new { message = "Période invalide (400 jours au maximum)." });

            var otQuery = _context.DemandeInterventions.AsNoTracking()
                .Where(d => d.IsActif && d.IdPlanPreventif != null && d.DatePlanifiee >= from && d.DatePlanifiee <= to);
            if (chaineId.HasValue) otQuery = otQuery.Where(d => d.IDChaineProduction == chaineId);
            var ots = await otQuery
                .Select(d => new
                {
                    Type = "ot",
                    Date = d.DatePlanifiee!.Value,
                    d.IdDemandeIntervention,
                    PlanId = d.IdPlanPreventif,
                    d.Titre,
                    d.StatusId,
                    Equipement = d.Equipement != null ? d.Equipement.Designation : null,
                    Technicien = d.Destinataire != null ? d.Destinataire.Prenom + " " + d.Destinataire.Nom : null
                })
                .ToListAsync();

            var planQuery = _context.PlansPreventifs.AsNoTracking().Where(p => p.IsActif && !p.Equipement.IsDeleted);
            if (chaineId.HasValue) planQuery = planQuery.Where(p => p.Equipement.IdChaineProduction == chaineId);
            var plans = await planQuery
                .Select(p => new
                {
                    Plan = p,
                    Equipement = p.Equipement.Designation,
                    Technicien = p.Technicien != null ? p.Technicien.Prenom + " " + p.Technicien.Nom : null
                })
                .ToListAsync();

            var projections = new List<object>();
            foreach (var item in plans)
            {
                var date = item.Plan.ProchaineEcheance.Date;
                var guard = 0;
                while (date <= to && guard++ < 400)
                {
                    if (date >= from)
                        projections.Add(new
                        {
                            Type = "prevision",
                            Date = date,
                            IdDemandeIntervention = (int?)null,
                            PlanId = (int?)item.Plan.Id,
                            item.Plan.Titre,
                            StatusId = 0,
                            item.Equipement,
                            item.Technicien
                        });
                    date = item.Plan.NextAfter(date);
                }
            }

            return Ok(ots.Cast<object>().Concat(projections));
        }

        /// <summary>Preventive compliance over the last <paramref name="days"/> days.</summary>
        [HttpGet("stats")]
        public async Task<ActionResult<object>> GetStats(int days = 90)
        {
            days = days is 7 or 30 or 90 or 365 ? days : 90;
            var today = DateTime.Today;
            var from = today.AddDays(-days);

            var dus = await _context.DemandeInterventions.AsNoTracking()
                .Where(d => d.IsActif && d.IdPlanPreventif != null && d.DatePlanifiee >= from && d.DatePlanifiee <= today &&
                            d.StatusId != DemandeInterventionController.StatusAnnulee)
                .Select(d => new { d.DatePlanifiee, d.DateRealisation, d.StatusId })
                .ToListAsync();

            var realises = dus.Count(d => d.DateRealisation.HasValue);
            var aLHeure = dus.Count(d => d.DateRealisation.HasValue && d.DateRealisation.Value.Date <= d.DatePlanifiee!.Value.AddDays(ToleranceJours));
            var enRetard = await _context.DemandeInterventions.CountAsync(d =>
                d.IsActif && d.IdPlanPreventif != null && d.DatePlanifiee < today &&
                d.StatusId <= DemandeInterventionController.StatusEnCours);
            var aVenir7 = await _context.DemandeInterventions.CountAsync(d =>
                d.IsActif && d.IdPlanPreventif != null && d.DatePlanifiee >= today && d.DatePlanifiee <= today.AddDays(7) &&
                d.StatusId <= DemandeInterventionController.StatusEnCours);
            var plansActifs = await _context.PlansPreventifs.CountAsync(p => p.IsActif);
            var equipementsCouverts = await _context.PlansPreventifs.Where(p => p.IsActif).Select(p => p.IdEquipement).Distinct().CountAsync();
            var equipements = await _context.Equipments.CountAsync(e => !e.IsDeleted);

            return Ok(new
            {
                days,
                dus = dus.Count,
                realises,
                aLHeure,
                tauxRespect = dus.Count == 0 ? (double?)null : Math.Round(100.0 * aLHeure / dus.Count, 1),
                tauxRealisation = dus.Count == 0 ? (double?)null : Math.Round(100.0 * realises / dus.Count, 1),
                enRetard,
                aVenir7,
                plansActifs,
                equipementsCouverts,
                equipements,
                couverture = equipements == 0 ? (double?)null : Math.Round(100.0 * equipementsCouverts / equipements, 1),
                toleranceJours = ToleranceJours
            });
        }
